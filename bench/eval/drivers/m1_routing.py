"""M1 — Routing accuracy.

Hand-labelled utterance set, run ``narrator.router.route``, score
per-intent precision / recall / F1 and overall accuracy.  Pure rule-based
classifier; no LLM, no service.

Output: ``bench/eval/results/m1_routing.json``
"""
from __future__ import annotations

import json
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

THIS = Path(__file__).resolve()
sys.path.insert(0, str(THIS.parents[3]))                 # repo root
sys.path.insert(0, str(THIS.parents[1]))                 # bench/eval/

from bench.eval._common import RESULTS, read_json, write_json, now_iso  # noqa: E402

from book.ir import Book, BookNode                                       # noqa: E402
from narrator import router                                                # noqa: E402

LABELS = THIS.parent / "labels_routing.json"


def _eslii_book() -> Book:
    """Lightweight Book for the resolvers (mirrors tests/test_router.py)."""
    root = BookNode(nid="b", kind="book", number=None, title="ESL",
                    page_start=1, page_end=999)
    # Build chapter+section nodes as the labelled utterances refer to.
    layout = [
        ("1", "Introduction", []),
        ("2", "Overview of Supervised Learning", []),
        ("3", "Linear Methods for Regression",
            [("3.4", "Shrinkage Methods")]),
        ("4", "Linear Methods for Classification", []),
        ("5", "Basis Expansions and Regularization",
            [("5.4", "Smoothing Splines"),
             ("5.8", "Regularization and Reproducing Kernel Hilbert Spaces"),
             ("5.8.1", "Spaces of Functions Generated by Kernels")]),
        ("7", "Model Assessment and Selection",
            [("7.3", "Bias-Variance Tradeoff")]),
        ("9", "Additive Models", [("9.2", "Tree-Based Methods")]),
        ("12", "Support Vector Machines and Flexible Discriminants",
            [("12.2", "The SVM as a Penalisation Method")]),
    ]
    for ch_num, ch_title, sections in layout:
        ch = BookNode(nid=f"b/ch{ch_num}", kind="chapter",
                      number=ch_num, title=ch_title,
                      page_start=10, page_end=99)
        for sec_num, sec_title in sections:
            slug_full = sec_num.replace(".", "_")
            kind = "section" if sec_num.count(".") == 1 else "subsection"
            ch.children.append(
                BookNode(nid=f"b/ch{ch_num}/s{slug_full}", kind=kind,
                         number=sec_num, title=sec_title,
                         page_start=10, page_end=99)
            )
        root.children.append(ch)
    return Book(title="ESL", author=None, source="", root=root,
                concepts={}, pages=[], figures=[])


def _classify_one(text: str, *, book: Book,
                  last_focus_topic: str = "ridge",
                  last_focus_nid: str = "b/ch5/s5_8/ss5_8_1") -> dict:
    r = router.route(text, book=book,
                     last_focus_nid=last_focus_nid,
                     last_focus_topic=last_focus_topic)
    return {"intent": r.intent, "control_action": r.control_action,
            "target_nid": r.target_nid, "topic": r.topic, "depth": r.depth}


def _per_intent_prf(rows: list[dict], intents: list[str]
                    ) -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    for k in intents:
        tp = sum(1 for r in rows if r["gold"] == k and r["pred"] == k)
        fp = sum(1 for r in rows if r["gold"] != k and r["pred"] == k)
        fn = sum(1 for r in rows if r["gold"] == k and r["pred"] != k)
        prec = tp / (tp + fp) if (tp + fp) else 0.0
        rec  = tp / (tp + fn) if (tp + fn) else 0.0
        f1   = (2 * prec * rec / (prec + rec)) if (prec + rec) else 0.0
        out[k] = {"support": tp + fn, "precision": prec,
                  "recall": rec, "f1": f1}
    return out


def main() -> None:
    spec = read_json(LABELS)
    intents = spec["intents"]
    book = _eslii_book()

    t0 = time.perf_counter()
    rows = []
    for u in spec["utterances"]:
        cls = _classify_one(u["text"], book=book)
        ok_intent = cls["intent"] == u["gold"]
        ok_action = True
        if u["gold"] == "control" and "action" in u:
            ok_action = cls["control_action"] == u["action"]
        rows.append({
            "text": u["text"], "gold": u["gold"], "pred": cls["intent"],
            "ok": ok_intent and ok_action,
            "pred_action": cls["control_action"],
            "expected_action": u.get("action", ""),
        })
    elapsed_ms = (time.perf_counter() - t0) * 1000.0

    n = len(rows)
    n_ok = sum(1 for r in rows if r["ok"])
    overall_acc = n_ok / n if n else 0.0

    confusion: dict[str, Counter[str]] = defaultdict(Counter)
    for r in rows:
        confusion[r["gold"]][r["pred"]] += 1

    per_intent = _per_intent_prf(rows, intents)
    macro_p = sum(v["precision"] for v in per_intent.values()) / len(intents)
    macro_r = sum(v["recall"]    for v in per_intent.values()) / len(intents)
    macro_f1 = (2 * macro_p * macro_r / (macro_p + macro_r)
                if (macro_p + macro_r) else 0.0)

    payload = {
        "metric": "M1_routing_accuracy",
        "ts": now_iso(),
        "labelled_set": str(LABELS.relative_to(THIS.parents[3])),
        "router_module": "narrator/router.py",
        "n_utterances": n,
        "n_correct": n_ok,
        "overall_accuracy": overall_acc,
        "macro_precision": macro_p,
        "macro_recall": macro_r,
        "macro_f1": macro_f1,
        "per_intent": per_intent,
        "confusion": {g: dict(c) for g, c in confusion.items()},
        "wall_ms": elapsed_ms,
        "wall_us_per_utterance": (elapsed_ms * 1000.0 / n) if n else 0.0,
        "rows": rows,
        "service_calls": 0,
        "api_cost_usd": 0.0,
    }
    out = RESULTS / "m1_routing.json"
    write_json(out, payload)
    print(f"[m1] wrote {out.relative_to(THIS.parents[3])}: "
          f"acc={overall_acc:.3f} F1={macro_f1:.3f} "
          f"({n} utterances in {elapsed_ms:.1f} ms)")


if __name__ == "__main__":
    main()
