@pytest.mark.parametrize("utterance", [
    "see also",
    "what else references this",
    "related sections",
    "where else is this used",
    "citation graph",
    "cross references",
])
def test_router_classifies_xref_explore(utterance):
    from narrator import router
    r = router.route(
        utterance,
        last_focus_nid="b/ch5/s5_8",
        last_focus_topic="reproducing kernels",
    )
    assert r.intent == router.INTENT_XREF_EXPLORE
    assert r.target_nid == "b/ch5/s5_8"


def test_router_xref_explore_without_focus():
    """No focus → still classifies; Session.ask falls back to QA."""
    from narrator import router
    r = router.route("see also")
    assert r.intent == router.INTENT_XREF_EXPLORE
    assert r.target_nid == ""
