"""Pin the citation-graph helpers + xref_explore planner +
xref_explore router intent.
"""
from __future__ import annotations

import pytest

from book.ir import Book, BookNode, CrossRef
from book import xref


def _book_with_xrefs() -> Book:
    """Tiny book mimicking ESLII's chapter-section layout with a
    deterministic citation graph."""
    root = BookNode(nid="b", kind="book", number=None,
                    title="ESL", page_start=1, page_end=999)
    ch3 = BookNode(nid="b/ch3", kind="chapter", number="3",
                   title="Linear Methods for Regression",
                   page_start=40, page_end=80)
    ch5 = BookNode(nid="b/ch5", kind="chapter", number="5",
                   title="Basis Expansions and Regularization",
                   page_start=100, page_end=200)
    s5_8 = BookNode(nid="b/ch5/s5_8", kind="section", number="5.8",
                    title="Reproducing Kernel Hilbert Spaces",
                    page_start=170, page_end=190)
    ss5_8_1 = BookNode(nid="b/ch5/s5_8/ss5_8_1", kind="subsection",
                       number="5.8.1", title="Spaces of Functions Generated by Kernels",
                       page_start=171, page_end=175)
    s5_8.children.append(ss5_8_1)
    ch5.children.append(s5_8)
    ch12 = BookNode(nid="b/ch12", kind="chapter", number="12",
                    title="Support Vector Machines",
                    page_start=400, page_end=440)
    s12_3 = BookNode(nid="b/ch12/s12_3", kind="section", number="12.3",
                     title="Support Vector Machines and Kernels",
                     page_start=420, page_end=430)
    ch12.children.append(s12_3)
    root.children.extend([ch3, ch5, ch12])

    # Hand-rolled citation graph:
    #   ch3 → ch5  (Chapter 5)
    #   ch5/s5_8 → ch12 (Chapter 12, twice)
    #   ch5/s5_8 → b/ch5/s5_8/ss5_8_1  (intra-subtree, should be filtered)
    #   ss5_8_1 → ch5/s5_8 (intra-subtree, should be filtered)
    #   ch12 → ch5/s5_8 (Section 5.8) — incoming from outside subtree
    #   ch12/s12_3 → ch5/s5_8 — incoming from outside subtree
    crs = [
        CrossRef(from_nid="b/ch3", to_nid="b/ch5",
                 label="Chapter 5", char_offset=0),
        CrossRef(from_nid="b/ch5/s5_8", to_nid="b/ch12",
                 label="Chapter 12", char_offset=10),
        CrossRef(from_nid="b/ch5/s5_8", to_nid="b/ch12",
                 label="Chapter 12", char_offset=400),
        CrossRef(from_nid="b/ch5/s5_8", to_nid="b/ch5/s5_8/ss5_8_1",
                 label="Section 5.8.1", char_offset=200),
        CrossRef(from_nid="b/ch5/s5_8/ss5_8_1", to_nid="b/ch5/s5_8",
                 label="Section 5.8", char_offset=50),
        CrossRef(from_nid="b/ch12", to_nid="b/ch5/s5_8",
                 label="Section 5.8", char_offset=20),
        CrossRef(from_nid="b/ch12/s12_3", to_nid="b/ch5/s5_8",
                 label="Section 5.8", char_offset=30),
    ]
    return Book(title="ESL", author=None, source="", root=root,
                concepts={}, pages=[], figures=[], cross_refs=crs)


# ---------------------------------------------------------------------------
# Outgoing / incoming
# ---------------------------------------------------------------------------

def test_outgoing_from_section_includes_descendants():
    book = _book_with_xrefs()
    refs = xref.outgoing(book, "b/ch5")
    # ch5 has no direct outgoing, but its descendant s5_8 has 2.
    targets = [cr.to_nid for cr in refs]
    assert "b/ch12" in targets


def test_outgoing_drops_self_subtree_refs():
    book = _book_with_xrefs()
    refs = xref.outgoing(book, "b/ch5/s5_8")
    # ch5/s5_8 → ss5_8_1 is intra-subtree.
    for cr in refs:
        assert cr.to_nid != "b/ch5/s5_8/ss5_8_1"


def test_incoming_drops_intra_subtree():
    book = _book_with_xrefs()
    refs = xref.incoming(book, "b/ch5/s5_8")
    # Only the ch12 + ch12/s12_3 references are external.
    sources = [cr.from_nid for cr in refs]
    assert "b/ch5/s5_8/ss5_8_1" not in sources
    assert "b/ch12" in sources
    assert "b/ch12/s12_3" in sources


def test_incoming_can_disable_filter():
    """Disabling both filters surfaces every raw incoming ref."""
    book = _book_with_xrefs()
    refs = xref.incoming(
        book, "b/ch5/s5_8",
        drop_intra_subtree=False, drop_self_refs=False,
    )
    sources = [cr.from_nid for cr in refs]
    assert "b/ch5/s5_8/ss5_8_1" in sources


