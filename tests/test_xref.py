def test_xref_explore_plan_has_both_directions():
    from narrator.qa import xref_explore
    book = _book_with_xrefs()
    plan = xref_explore(book, "b/ch5/s5_8")
    assert plan.meta["mode"] == "xref_explore"
    assert plan.meta["focus_nid"] == "b/ch5/s5_8"
    text = " ".join(c.text for c in plan.clauses)
    assert "references" in text.lower()
    assert "cited" in text.lower()
    # Outgoing labels in narration.
    assert "Chapter 12" in text


def test_xref_explore_handles_unknown_nid():
    from narrator.qa import xref_explore
    book = _book_with_xrefs()
    plan = xref_explore(book, "b/nonsense")
    assert any("focus" in c.text.lower() or "ask me" in c.text.lower()
               for c in plan.clauses)


def test_xref_explore_handles_missing_outgoing():
    """Section that cites nothing should still produce a sensible plan."""
    from narrator.qa import xref_explore
    book = _book_with_xrefs()
    plan = xref_explore(book, "b/ch3")
    text = " ".join(c.text for c in plan.clauses)
    # ch3 → ch5 is the only outgoing; cited by nothing in the
    # fixture.  Plan should mention this gracefully.
    assert "cite" in text.lower() or "citation" in text.lower() or "no" in text.lower()


