def test_group_by_label_counts():
    book = _book_with_xrefs()
    refs = xref.outgoing(book, "b/ch5/s5_8")
    grouped = xref.group_by_label(refs)
    # "Chapter 12" appears twice in the fixture.
    assert grouped[0] == ("Chapter 12", 2)


def test_group_by_source_for_incoming():
    book = _book_with_xrefs()
    refs = xref.incoming(book, "b/ch5/s5_8")
    sources = [nid for nid, _, _ in xref.group_by_source(refs)]
    assert sources[:2] == sorted(["b/ch12", "b/ch12/s12_3"])
    # Each source contributes 1 ref in the fixture.
    counts = [c for _, c, _ in xref.group_by_source(refs)]
    assert counts == [1, 1]


def test_most_cited_orders_by_count():
    book = _book_with_xrefs()
    top = xref.most_cited(book, k=3)
    # b/ch5/s5_8 has 3 incoming (after self-ref filter).
    nids = [n for n, _ in top]
    assert "b/ch5/s5_8" in nids
    counts = dict(top)
    assert counts["b/ch5/s5_8"] >= 2


