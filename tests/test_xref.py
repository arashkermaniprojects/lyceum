def test_citation_path_finds_two_hop():
    book = _book_with_xrefs()
    path = xref.citation_path(book, "b/ch3", "b/ch12", max_hops=3)
    # ch3 → ch5 → ch12 takes two hops.
    assert len(path) == 2
    assert path[0].to_nid == "b/ch5"
    assert path[1].from_nid in {"b/ch5", "b/ch5/s5_8"}


def test_citation_path_finds_subtree_containment():
    """When the target sits inside a node we can already reach, the
    path stops at the containing ancestor — the cited chapter
    contains the target subsection, so 1 hop is enough."""
    book = _book_with_xrefs()
    path = xref.citation_path(book, "b/ch3", "b/ch5/s5_8/ss5_8_1",
                              max_hops=1)
    assert len(path) == 1
    assert path[0].from_nid == "b/ch3"
    assert path[0].to_nid == "b/ch5"


def test_citation_path_returns_empty_when_unreachable():
    """No edges at all from a leaf with nothing cited."""
    book = _book_with_xrefs()
    path = xref.citation_path(book, "b/ch5/s5_8/ss5_8_1", "b/ch3",
                              max_hops=2)
    assert path == []


