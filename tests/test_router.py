@pytest.mark.parametrize("utterance", [
    "what have we covered",
    "what did you cover so far",
    "recap",
    "recap so far",
    "summarise what we discussed",
    "where are we so far",
])
def test_recap_intent(utterance):
    r = router.route(utterance, book=_mini_book())
    assert r.intent == router.INTENT_RECAP


@pytest.mark.parametrize("utterance,expected_topic", [
    ("show me regularization again", "regularization"),
    ("explain ridge regression again", "ridge regression"),
    ("repeat that", ""),
    ("once more", ""),
    ("again", ""),
])
def test_reshow_intent(utterance, expected_topic):
    r = router.route(
        utterance, book=_mini_book(),
        last_focus_topic="ridge",
    )
    assert r.intent == router.INTENT_RESHOW
    if expected_topic:
        assert expected_topic.lower() in r.topic.lower()
    else:
        # Bare reshow falls back to last_focus_topic.
        assert r.topic == "ridge"


@pytest.mark.parametrize("utterance,expected_action", [
    ("forget that", "forget"),
    ("forget everything", "forget"),
    ("start fresh", "forget"),
    ("reset", "forget"),
    ("clear what we covered", "forget"),
])
def test_forget_intent(utterance, expected_action):
    r = router.route(utterance)
    assert r.intent == router.INTENT_CONTROL
    assert r.control_action == expected_action
